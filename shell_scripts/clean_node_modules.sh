#!/usr/bin/env bash
#
# clean_node_modules.sh
#
# Recursively finds and deletes all `node_modules` directories under a
# given path (default: current directory).
#
# Usage:
#   ./clean_node_modules.sh [path] [--yes]
#
#   path    Directory to search under (default: current directory)
#   --yes   Skip the confirmation prompt and delete immediately
#
# Examples:
#   ./clean_node_modules.sh                # search from cwd, ask first
#   ./clean_node_modules.sh ~/projects      # search under ~/projects
#   ./clean_node_modules.sh ~/projects --yes  # no confirmation

set -euo pipefail

TARGET_DIR="."
ASSUME_YES=false

for arg in "$@"; do
  case "$arg" in
    --yes|-y)
      ASSUME_YES=true
      ;;
    *)
      TARGET_DIR="$arg"
      ;;
  esac
done

if [[ ! -d "$TARGET_DIR" ]]; then
  echo "Error: '$TARGET_DIR' is not a directory." >&2
  exit 1
fi

echo "Searching for node_modules directories under: $(realpath "$TARGET_DIR")"
echo

# Find all node_modules directories, but don't descend into ones already
# found (no point recursing into a node_modules you're about to delete).
mapfile -t DIRS < <(find "$TARGET_DIR" -type d -name "node_modules" -prune)

if [[ ${#DIRS[@]} -eq 0 ]]; then
  echo "No node_modules directories found."
  exit 0
fi

TOTAL_SIZE=0
echo "Found ${#DIRS[@]} node_modules director$([ ${#DIRS[@]} -eq 1 ] && echo y || echo ies):"
for dir in "${DIRS[@]}"; do
  size=$(du -sh "$dir" 2>/dev/null | cut -f1)
  echo "  $dir ($size)"
done
echo

if [[ "$ASSUME_YES" != true ]]; then
  read -r -p "Delete all of the above? [y/N] " confirm
  if [[ ! "$confirm" =~ ^[Yy]$ ]]; then
    echo "Aborted. Nothing was deleted."
    exit 0
  fi
fi

for dir in "${DIRS[@]}"; do
  echo "Deleting $dir ..."
  rm -rf -- "$dir"
done

echo
echo "Done. Deleted ${#DIRS[@]} node_modules director$([ ${#DIRS[@]} -eq 1 ] && echo y || echo ies)."
